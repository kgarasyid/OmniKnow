import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const out=fileURLToPath(new URL('./',import.meta.url));
const text=await fs.readFile(new URL('../dummy-ppt/01-agen-import.csv',import.meta.url),'utf8');
const source=await Workbook.fromCSV(text.replace(/^\uFEFF/,''),{sheetName:'Source'});
const records=source.worksheets.getItem('Source').getRange('A2:O37').values;
const wb=Workbook.create(),s=wb.worksheets.add('Raw ASK');
s.getRange('A1:I1').values=[['agent_id','agent_name','area','region','ctp','assessment_date','attitude','skill','knowledge']];
s.getRange('A2:I37').values=records.map(r=>[r[0],r[1],r[2],r[3],r[4],new Date(String(r[14]).slice(0,10)+'T00:00:00Z'),Number(r[7]),Number(r[8]),Number(r[9])]);
s.showGridLines=false;
s.getRange('A1:I37').format.font={name:'Arial',size:11,color:'#172C45'};
s.getRange('A1:I37').format.rowHeight=25;
s.getRange('A1:I37').format.verticalAlignment='center';
s.getRange('A1:I1').format={fill:'#173D64',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},rowHeight:32};
s.getRange('A1:I1').format.horizontalAlignment='center';
s.getRange('A1:E37').format.columnWidth=24;
s.getRange('F1:F37').format.columnWidth=22;
s.getRange('G1:I37').format.columnWidth=17;
s.getRange('F2:F37').setNumberFormat('yyyy-mm-dd');
s.getRange('G2:I37').setNumberFormat('0');
s.freezePanes.freezeRows(1);s.freezePanes.freezeColumns(2);
s.tables.add('A1:I37',true,'RawASK');
wb.recalculate();
const vals=s.getRange('G2:I37').values;
if(records.length!==36||vals.some(r=>r.some(v=>typeof v!=='number'||v<0||v>100)))throw new Error('Invalid ASK records');
console.log((await wb.inspect({kind:'table',range:'Raw ASK!A1:I4',include:'values',tableMaxRows:4,tableMaxCols:9})).ndjson);
const preview=await wb.render({sheetName:'Raw ASK',range:'A1:I9',scale:1.5,format:'png'});
await fs.writeFile(out+'raw-ask-preview.png',new Uint8Array(await preview.arrayBuffer()));
await(await SpreadsheetFile.exportXlsx(wb)).save(out+'OmniKnow-Dummy-Raw-ASK.xlsx');
console.log('Saved one sheet, 36 fictional raw ASK records, no calculated scores.');
